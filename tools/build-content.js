#!/usr/bin/env node
/* Bundles content/*.json into js/content/bundle.js so the game also works from file:// and offline.
   Usage: node tools/build-content.js   (run it after editing anything in content/) */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'content');
const read = (f) => {
  const p = path.join(dir, f);
  try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch (e) { console.error(`✗ ${f}: ${e.message}`); process.exit(1); }
};

const manifest = read('manifest.json');
const out = {};
Object.entries(manifest).forEach(([key, val]) => {
  if (key.startsWith('_')) return;
  if (key === 'maps') { out.maps = {}; val.forEach((id) => { out.maps[id] = read(`maps/${id}.json`); }); }
  else out[key] = read(val);
});

const js = `/* AUTO-GENERATED by tools/build-content.js from content/*.json — do not edit by hand. */\nwindow.BH = window.BH || {};\nBH.CONTENT_BUNDLE = ${JSON.stringify(out)};\n`;
fs.mkdirSync(path.join(root, 'js/content'), { recursive: true });
fs.writeFileSync(path.join(root, 'js/content/bundle.js'), js);
console.log(`✓ js/content/bundle.js (${(js.length / 1024).toFixed(1)} KB, ${Object.keys(out.maps).length} maps)`);
